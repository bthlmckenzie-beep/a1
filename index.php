        <div class="section-header">
          <span class="badge-tag">Frequently Answered</span>
          <h2 class="section-title">Atelier & Craftsmanship Inquiries</h2>
          <p class="section-subtitle">Understanding the engineering, materials, and bespoke commissioning process behind ClutchParade accessories.</p>
        </div>

        <div class="accordion-wrapper">
          <div class="accordion-item active">
            <button class="accordion-header">
              <span>What distinguishes a true luxury minaudière from a standard evening bag?</span>
              <span class="accordion-icon">+</span>
            </button>
            <div class="accordion-body">
              A genuine minaudière is engineered as a rigid jewelry case rather than a flexible pouch. It features a solid metal chassis (typically jeweler's brass or precision-milled aluminum) engineered to precise geometric tolerances, fitted with a custom spring hinge and acoustic tension clasp. The interior is compartmentalized with bespoke compartments for evening essentials, all lined in delicate French lambskin or ribbed silk faille.
            </div>
          </div>

          <div class="accordion-item">
            <button class="accordion-header">
              <span>Why is hand saddle stitching superior to machine lockstitching?</span>
              <span class="accordion-icon">+</span>
            </button>
            <div class="accordion-body">
              A machine lockstitch uses an upper thread and bobbin thread looped together in the center of the leather. If one thread wears through or breaks, the entire seam can effortlessly unravel like a zipper. In contrast, the traditional French saddle stitch employs two needles traveling simultaneously in opposite directions through each awl-pierced hole. If a saddle stitch is severed, the surrounding stitches remain friction-locked in place, ensuring decades of structural integrity.
            </div>
          </div>

          <div class="accordion-item">
            <button class="accordion-header">
              <span>How should delicate box calf and goat leather clutches be stored between galas?</span>
              <span class="accordion-icon">+</span>
            </button>
            <div class="accordion-body">
              Always store your clutch inside an unbleached, breathable 100% cotton dust bag in a climate-controlled space maintained between 45% and 55% relative humidity. Lightly fill the interior with acid-free tissue paper to maintain structural wall tension without overstuffing. Keep metallic hardware away from direct humidity to prevent micro-oxidation, and avoid plastic storage containers which trap moisture and induce mold bloom.
            </div>
          </div>

          <div class="accordion-item">
            <button class="accordion-header">
              <span>What is the typical timeframe for a bespoke clutch commission?</span>
              <span class="accordion-icon">+</span>
            </button>
            <div class="accordion-body">
              A bespoke evening clutch commission typically requires 6 to 12 weeks from initial architectural rendering to final hand-delivery. This duration encompasses hide selection from French tanneries, custom hardware casting or plating, precision hand saddle-stitching, seven-step edge burnishing cycles, and rigorous quality inspection.
            </div>
          </div>
